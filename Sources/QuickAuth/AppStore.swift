import AppKit
import LocalAuthentication
import QuickAuthCore
import SwiftUI

@MainActor
final class AppStore: ObservableObject {
  @Published private(set) var accounts: [OTPAccount] = []
  @Published var query = ""
  @Published var favoritesOnly = false
  @Published var copiedID: UUID?
  @Published var message: String?
  @Published var error: String?
  @Published private(set) var isLocked = false
  @Published private(set) var isUnlocking = false
  @Published private(set) var loadFailed = false
  let demo: Bool
  private let vault = KeychainVault()
  private var clipboardChange: Int?
  private var clearTask: Task<Void, Never>?
  private var unlockContext: LAContext?
  private var lockGeneration = 0

  init(demo: Bool = false) {
    self.demo = demo
    if demo {
      let names = [
        ("GitHub", "hello@example.com"), ("Google", "work@example.com"),
        ("Cloudflare", "team@example.com"), ("Microsoft", "hello@example.com"),
      ]
      accounts = names.enumerated().compactMap { index, value in
        try? OTPAccount(
          issuer: value.0, account: value.1, secret: Data("demo-only-secret-\(index)".utf8),
          favorite: index == 0)
      }
    } else if UserDefaults.standard.bool(forKey: "vaultRequiresUnlock") {
      isLocked = true
    } else {
      reload()
    }
  }

  var visibleAccounts: [OTPAccount] {
    accounts.filter { $0.matches(query) && (!favoritesOnly || $0.favorite) }
      .sorted {
        if $0.favorite != $1.favorite { return $0.favorite }
        let title = $0.title.localizedStandardCompare($1.title)
        if title != .orderedSame { return title == .orderedAscending }
        return $0.subtitle.localizedStandardCompare($1.subtitle) == .orderedAscending
      }
  }

  func reload() {
    guard !demo else { return }
    do {
      accounts = try vault.load()
      loadFailed = false
      error = nil
    } catch {
      accounts = []
      loadFailed = true
      self.error = error.localizedDescription
    }
  }

  func commit(_ next: [OTPAccount]) throws {
    guard !isLocked, !loadFailed else { throw AuthError.invalid("账户尚未解锁或读取失败，请先恢复访问。") }
    if !demo { try vault.save(next) }
    accounts = next
  }

  func merge(_ incoming: [OTPAccount]) throws -> ImportMerge {
    let merge = ImportMerge(existing: accounts, incoming: incoming)
    if merge.added > 0 { try commit(merge.accounts) }
    message = "已导入 \(merge.added) 个账户，跳过 \(merge.duplicates) 个重复账户"
    return merge
  }

  func toggleFavorite(_ account: OTPAccount) {
    var next = accounts
    guard let index = next.firstIndex(where: { $0.id == account.id }) else { return }
    next[index].favorite.toggle()
    do { try commit(next) } catch { self.error = error.localizedDescription }
  }

  func delete(_ account: OTPAccount) {
    do {
      try commit(accounts.filter { $0.id != account.id })
      clearClipboard()
    } catch { self.error = error.localizedDescription }
  }

  func advance(_ account: OTPAccount) {
    guard account.kind == .hotp else { return }
    var next = accounts
    guard let index = next.firstIndex(where: { $0.id == account.id }),
      next[index].counter < UInt64.max
    else {
      error = "计数器已达到上限。"
      return
    }
    next[index].counter += 1
    do {
      try commit(next)
      copiedID = nil
    } catch { self.error = error.localizedDescription }
  }

  func copy(_ account: OTPAccount) {
    guard !isLocked, !loadFailed else { return }
    let pasteboard = NSPasteboard.general
    pasteboard.clearContents()
    let item = NSPasteboardItem()
    item.setString(account.code(), forType: .string)
    // Tell compatible clipboard managers that this content is sensitive and transient.
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
    item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    guard pasteboard.writeObjects([item]) else {
      error = "无法复制到剪贴板。"
      return
    }
    clipboardChange = pasteboard.changeCount
    copiedID = account.id
    clearTask?.cancel()
    clearTask = Task { [weak self] in
      try? await Task.sleep(nanoseconds: 2_000_000_000)
      guard !Task.isCancelled else { return }
      self?.copiedID = nil
      try? await Task.sleep(nanoseconds: 28_000_000_000)
      guard !Task.isCancelled else { return }
      self?.clearClipboard()
    }
  }

  func clearClipboard() {
    if let change = clipboardChange, NSPasteboard.general.changeCount == change {
      NSPasteboard.general.clearContents()
    }
    clipboardChange = nil
    copiedID = nil
  }

  func lock() {
    guard !demo else { return }
    lockGeneration += 1
    UserDefaults.standard.set(true, forKey: "vaultRequiresUnlock")
    unlockContext?.invalidate()
    unlockContext = nil
    isUnlocking = false
    clearTask?.cancel()
    clearClipboard()
    accounts = []
    query = ""
    message = nil
    error = nil
    isLocked = true
    NotificationCenter.default.post(name: .vaultLocked, object: nil)
  }

  func unlock() {
    guard !isUnlocking else { return }
    let context = LAContext()
    var reason: NSError?
    guard context.canEvaluatePolicy(.deviceOwnerAuthentication, error: &reason) else {
      error = "系统身份验证不可用，请检查 Mac 的登录密码设置后重试。"
      return
    }
    isUnlocking = true
    unlockContext = context
    let generation = lockGeneration
    context.evaluatePolicy(.deviceOwnerAuthentication, localizedReason: "解锁 Quick Auth 验证码") {
      [weak self] success, _ in
      Task { @MainActor in
        guard let self, self.lockGeneration == generation else { return }
        self.isUnlocking = false
        self.unlockContext = nil
        if success {
          self.reload()
          self.isLocked = self.loadFailed
          if !self.isLocked { UserDefaults.standard.set(false, forKey: "vaultRequiresUnlock") }
        }
      }
    }
  }
}

extension Notification.Name {
  static let vaultLocked = Notification.Name("QuickAuth.vaultLocked")
  static let focusSearch = Notification.Name("QuickAuth.focusSearch")
}
